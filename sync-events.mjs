// Copies the real events from events.ts into member-events-demo.html.
// The demo is a plain HTML file (no build step), so it can't import TypeScript itself.
// Run after editing events.ts:   node sync-events.mjs   (Node 22.18+ / 24, which run .ts directly)

import { readFileSync, writeFileSync } from "node:fs";
import { EVENTS } from "./events.ts";

const HTML = new URL("./member-events-demo.html", import.meta.url);
const START = "/* EVENTS_TS:START (generated by sync-events.mjs from events.ts; don't edit by hand) */";
const END = "/* EVENTS_TS:END */";

// Only the fields the demo uses
const FIELDS = [
  "id", "kind", "title", "days", "time", "location", "description", "popupDescription", "calTitle", "media", "posters", "logo", "speaker",
  // "More details" sheet
  "popupTitle", "popupDate", "sessions", "audience", "highlights", "takeawaysTitle", "takeaways", "modulesTitle", "moduleLabel", "outcomeLabel", "modules", "closingNote",
];
const data = EVENTS.map((e) => Object.fromEntries(FIELDS.filter((k) => e[k] !== undefined).map((k) => [k, e[k]])));

const html = readFileSync(HTML, "utf8");
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < a) throw new Error("EVENTS_TS markers not found in member-events-demo.html");

const block = `${START}\nconst EVENTS_TS = ${JSON.stringify(data, null, 2).replace(/<\/script/gi, "<\\/script")};\n`;
writeFileSync(HTML, html.slice(0, a) + block + html.slice(b));
console.log(`Synced ${data.length} events into member-events-demo.html`);
